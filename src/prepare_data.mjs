// Collects the team's submissions into one small data file for the site.
// Usage: node src/prepare_data.mjs   (run from the repo root; writes src/site-data.js)
import fs from 'fs';

const read = p => fs.readFileSync(p, 'utf8');
const csv = p => { const [head, ...rows] = read(p).trim().split(/\r?\n/); const keys = head.split(','); return rows.map(r => Object.fromEntries(r.split(',').map((v, i) => [keys[i], v]))); };

// AG01 (Arrington): average one-way fare from ATL to each destination, all 2022 searches
const map = Object.fromEntries(csv('submissions/Arrington_Visualizations/atl_airport_fares.csv').map(r => [r.destination_airport, {
  avg: +r.avg_fare, min: +r.min_fare, n: +r.itinerary_count, state: r.destination_state
}]));

// CZ-01 / CZ-03 (Cynthia): staircase medians + Labor Day diary flights (ATL routes only, the map's origin)
const cz = JSON.parse(read('submissions/cynthia-cz01-cz03/website_data.json'));
const diary = Object.fromEntries(Object.entries(cz.SITE_DIARY).filter(([k]) => k.startsWith('ATL-')));

// YH-02 (Yuhan): overall nonstop vs connecting medians + same-route medians from ATL
const yh = JSON.parse(read('submissions/yuhan-q7/Q7_website_data.json'));
const HK = { 'Memorial Day': 'mem', 'July 4': 'jul', 'Labor Day': 'lab', 'Non-holiday': 'non' };
const bars = {}, byRoute = {};
for (const r of yh.overall) (bars[HK[r.holiday]] ??= {})[r.flightType] = { fare: r.medianFare, n: r.quoteCount };
for (const r of yh.byRoute) {
  if (r.startingAirport !== 'ATL' || !r.hasBothFlightTypes) continue;
  ((byRoute[r.destinationAirport] ??= {})[HK[r.holiday]] ??= {})[r.flightType] = { fare: r.medianFare, n: r.quoteCount };
}

const SITE_DATA = {
  source: 'Expedia Flight Prices (Kaggle, dilwong/flightprices), one-way fares searched Apr 16 - Oct 5, 2022',
  map, KP: cz.KP, diary, bars, byRoute
};
fs.writeFileSync('src/site-data.js', '// Generated by src/prepare_data.mjs from submissions/. Do not edit by hand.\nconst SITE_DATA = ' + JSON.stringify(SITE_DATA) + ';\n');
console.log('wrote src/site-data.js',
  Object.keys(map).length, 'map destinations,', Object.keys(diary).length, 'diary routes,', Object.keys(byRoute).length, 'same-route comparisons');
